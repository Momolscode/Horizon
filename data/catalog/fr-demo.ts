type PlaceInput = Omit<Place, "practical" | "sourceIds" | "verification" | "fictional" | "sponsored" | "locationPrecision" | "lesserKnown"> & {
  practical?: Partial<Place["practical"]>;
  lesserKnown?: boolean;
  fictional?: boolean;
};

function place(input: PlaceInput): Place {
  const fictional = input.fictional ?? false;
  return {
    ...input,
    lesserKnown: input.lesserKnown ?? false,
    locationPrecision: "approximate",
    practical: {
      price: unknown,
      openingHours: unknown,
      visitMinutes: unknown,
      accessibility: unknown,
      booking: unknown,
      website: unknown,
      ...input.practical,
    },
    sourceIds: fictional ? [FIXTURE] : [EDITORIAL],
    verification: fictional ? FICTIONAL : UNVERIFIED,
    fictional,
    sponsored: null,
  };
}

